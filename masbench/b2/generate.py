"""Generate the B2 scenario directories from the environment modules.

    python -m masbench.b2.generate

Every module in `masbench/b2/envs/` offers `build_cases() -> [(Scenario, [Case, ...]), ...]`.
"""
from __future__ import annotations

import importlib
import pkgutil

from masbench import io
from masbench.b2 import envs
from masbench.schema import Case, Scenario

HEADER = "# Generated by `python -m masbench.b2.generate` from masbench/b2/envs/. Do not edit."


def build_all() -> list[tuple[Scenario, list[Case]]]:
    out: list[tuple[Scenario, list[Case]]] = []
    for m in sorted(pkgutil.iter_modules(envs.__path__), key=lambda m: m.name):
        if not m.name.startswith("_"):
            out += importlib.import_module(f"{envs.__name__}.{m.name}").build_cases()
    return out


def main() -> None:
    for scn, cases in build_all():
        io.write_scenario(scn, HEADER)
        io.write_cases(scn.id, cases)
        kinds = [c.kind for c in cases]
        print(f"{scn.id}: {kinds.count('attack')} attack, {kinds.count('benign')} twin, "
              f"{kinds.count('control')} control cases")


if __name__ == "__main__":
    main()
