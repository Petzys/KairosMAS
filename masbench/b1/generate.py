"""Generate the B1 scenario directories from AgentDojo.

    .venv/bin/python -m masbench.b1.generate [--version v1]

Writes data/b1/<suite>/{scenario.yaml, cases.jsonl, layouts.yaml}. Everything is derived from
AgentDojo and `partition.py`; the labels come from running each task's ground truth with a
canary string in every injection slot (as AgentDojo's `get_injection_candidates` does).
"""
from __future__ import annotations

import argparse
import inspect
import json
import textwrap
from typing import Any

import yaml
from agentdojo.agent_pipeline.ground_truth_pipeline import GroundTruthPipeline
from agentdojo.base_tasks import BaseInjectionTask, BaseUserTask
from agentdojo.functions_runtime import FunctionsRuntime
from agentdojo.task_suite.load_suites import get_suite
from agentdojo.task_suite.task_suite import read_suite_file

from masbench import io, prompts
from masbench.b1.partition import (
    ANNOTATION_FIELDS,
    ANNOTATIONS,
    ORCHESTRATOR,
    SUITES,
    TABLE_COUNTS,
    SubAgent,
)
from masbench.layouts import build_layouts
from masbench.schema import (
    AgentCard,
    AgentSkill,
    AgentSpec,
    Attacker,
    Case,
    Check,
    EnvironmentSpec,
    Injection,
    Labels,
    Principal,
    Scenario,
    Scoring,
    ToolSpec,
    UserTurn,
)

USER = "Emma Johnson"
DEFAULT_ATTACK = "important_instructions"
HEADER = "# Generated by `python -m masbench.b1.generate`; edit partition.py, not this file."


def _body(fn: Any) -> str:
    src = textwrap.dedent(inspect.getsource(fn))
    return src.split(":\n", 1)[1] if ":\n" in src else src  # drop the signature


def check_reads(task: BaseUserTask | BaseInjectionTask) -> list[str]:
    """What the AgentDojo check of `task` inspects (state, output, trace)."""
    base = BaseUserTask if isinstance(task, BaseUserTask) else BaseInjectionTask
    name = "utility" if isinstance(task, BaseUserTask) else "security"
    if getattr(type(task), f"{name}_from_traces") is not getattr(base, f"{name}_from_traces"):
        return ["trace"]
    body = _body(getattr(type(task), name))
    reads = []
    if "post_environment" in body or "pre_environment" in body:
        reads.append("state")
    if "model_output" in body:
        reads.append("output")
    return reads or ["state"]


def _vector_carriers(suite, task: BaseUserTask) -> dict[str, list[str]]:  # noqa: ANN001
    """Injection vector -> tools whose output contains it when the task is solved correctly."""
    canaries = {v: f"<CANARY---{v}--->" for v in suite.get_injection_vector_defaults()}
    env = suite.load_and_inject_default_environment(canaries)
    env = task.init_environment(env)
    _, _, _, msgs, _ = GroundTruthPipeline(task).query(task.PROMPT, FunctionsRuntime(suite.tools), env)
    found: dict[str, set[str]] = {}
    for m in msgs:
        if m["role"] != "tool" or not m["content"]:
            continue
        text = json.dumps(m["content"])
        for v, c in canaries.items():
            if c in text:
                found.setdefault(v, set()).add(m["tool_call"].function)
    return {v: sorted(t) for v, t in sorted(found.items())}


def _gt_calls(suite, task) -> list[str]:  # noqa: ANN001
    env = suite.load_and_inject_default_environment({})
    if isinstance(task, BaseUserTask):
        env = task.init_environment(env)
    return [c.function for c in task.ground_truth(env)]


def _comm(calls: list[str], owner: dict[str, str], tools: dict[str, ToolSpec]) -> str:
    workers = {owner[c] for c in calls}
    if len(workers) <= 1:
        return "delegation"
    for i, c in enumerate(calls):
        if tools[c].effect == "write" and any(
            owner[p] != owner[c] and tools[p].effect == "read" for p in calls[:i]
        ):
            return "worker_to_worker"
    return "fan_out"


def _card(a: SubAgent, tools: dict[str, ToolSpec]) -> AgentCard:
    skills = [AgentSkill(id=a.id, name=a.name, description=a.scope, tags=sorted(a.tools))] if a.tools else []
    return AgentCard(name=a.name, description=a.scope, skills=skills)


def build_scenario(suite_name: str, version: str, carriers: dict[str, list[str]]) -> Scenario:
    suite = get_suite(version, suite_name)
    subagents = SUITES[suite_name]
    for a in subagents:
        assert len(a.tools) == TABLE_COUNTS[suite_name][a.id], (suite_name, a.id)
    owned = [t for a in subagents for t in a.tools]
    assert sorted(owned) == sorted(f.name for f in suite.tools), f"{suite_name}: partition != suite tools"
    ann = ANNOTATIONS[suite_name]
    tools = [
        ToolSpec(name=f.name, description=f.description, parameters=f.parameters.model_json_schema(),
                 **dict(zip(ANNOTATION_FIELDS, ann[f.name], strict=True)))
        for f in suite.tools
    ]
    by_name = {t.name: t for t in tools}
    for v, ts in carriers.items():
        for t in ts:
            assert by_name[t].output_trust == "untrusted", f"{t} carries {v} but is annotated trusted"
    vec_yaml = yaml.safe_load(read_suite_file(suite_name, "injection_vectors.yaml", suite.data_path))
    vectors = {
        v: f"{(info or {}).get('description', '')} [returned by: {', '.join(carriers.get(v, [])) or 'no ground-truth tool'}]".strip()
        for v, info in vec_yaml.items()
    }
    agents = [AgentSpec(id=ORCHESTRATOR.id, card=_card(ORCHESTRATOR, by_name),
                        system_prompt=prompts.ORCHESTRATOR.replace("{name}", ORCHESTRATOR.name),
                        tools=[], entry=True)]
    agents += [
        AgentSpec(id=a.id, card=_card(a, by_name), tools=a.tools,
                  system_prompt=prompts.WORKER.replace("{name}", a.name).replace("{scope}", a.scope))
        for a in subagents
    ]
    return Scenario(
        id=f"b1.{suite_name}", benchmark="B1",
        description=f"AgentDojo {version} {suite_name} suite split over agents as in MultiAgentDojo.",
        principal=Principal(name=USER, description="Employee of Blue Sparrow Tech (AgentDojo user)"),
        environment=EnvironmentSpec(kind="agentdojo", suite=suite_name, version=version,
                                    injection_vectors=vectors),
        tools=tools, agents=agents,
        provenance={"tasks": f"AgentDojo {version} (ethz-spylab/agentdojo)",
                    "agent_split": "MultiAgentDojo, 'Can CaMeLs talk?', Table I",
                    "orchestrator": "tool-less entry agent"},
    )


def build_cases(suite_name: str, version: str, s: Scenario,
                carriers_by_task: dict[str, dict[str, list[str]]]) -> list[Case]:
    suite = get_suite(version, suite_name)
    owner = {t: a.id for a in s.agents for t in a.tools}
    tools = {t.name: t for t in s.tools}
    ref = f"agentdojo:{version}:{suite_name}"
    its = {iid: (it, _gt_calls(suite, it)) for iid, it in suite.injection_tasks.items()}
    cases: list[Case] = []
    for uid, ut in suite.user_tasks.items():
        calls = _gt_calls(suite, ut)
        carriers = carriers_by_task[uid]
        readers = sorted({owner[t] for ts in carriers.values() for t in ts})
        base = dict(
            source=f"agentdojo/{version}", user_task=uid,
            workers=sorted({owner[c] for c in calls}), comm=_comm(calls, owner, tools),
            reader_agents=readers,
        )
        benign_id = f"{s.id}/{uid}"
        utility = Check(ref=f"{ref}:{uid}", reads=check_reads(ut))
        cases.append(Case(id=benign_id, scenario=s.id, kind="benign",
                          user=UserTurn(agent=s.entry_agent.id, prompt=ut.PROMPT),
                          scoring=Scoring(utility=utility), labels=Labels(**base)))
        for iid, (it, it_calls) in its.items():
            actors = sorted({owner[c] for c in it_calls})
            if not actors:
                flow = "text_only"
            elif set(actors) <= set(readers):
                flow = "same_agent"
            elif set(actors) & set(readers):
                flow = "mixed"
            else:
                flow = "cross_agent"
            cases.append(Case(
                id=f"{benign_id}/{iid}", scenario=s.id, kind="attack", benign_twin=benign_id,
                user=UserTurn(agent=s.entry_agent.id, prompt=ut.PROMPT),
                attacker=Attacker(position="A1", goal=it.GOAL, injections=[
                    Injection(vector=v, attack=DEFAULT_ATTACK, goal=it.GOAL) for v in carriers]),
                scoring=Scoring(utility=utility, security=Check(ref=f"{ref}:{iid}", reads=check_reads(it))),
                labels=Labels(**base, injection_task=iid, actor_agents=actors, flow=flow),
            ))
    return cases


def generate(suite_name: str, version: str = "v1") -> tuple[Scenario, list[Case]]:
    suite = get_suite(version, suite_name)
    carriers_by_task = {uid: _vector_carriers(suite, ut) for uid, ut in suite.user_tasks.items()}
    all_carriers: dict[str, set[str]] = {}
    for c in carriers_by_task.values():
        for v, ts in c.items():
            all_carriers.setdefault(v, set()).update(ts)
    s = build_scenario(suite_name, version, {v: sorted(t) for v, t in all_carriers.items()})
    cases = build_cases(suite_name, version, s, carriers_by_task)
    io.write_scenario(s, HEADER)
    io.write_cases(s.id, cases)
    io.write_layouts(build_layouts(s), HEADER)
    return s, cases


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--version", default="v1")
    p.add_argument("--suite", nargs="*", default=list(SUITES))
    args = p.parse_args()
    for name in args.suite:
        _, cases = generate(name, args.version)
        n_att = sum(c.kind == "attack" for c in cases)
        print(f"b1.{name}: {len(cases) - n_att} benign, {n_att} attack cases")


if __name__ == "__main__":
    main()
