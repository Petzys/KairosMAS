"""KAIROS MAS policies for B1: one policy per agent, one per cluster and layout.

Lives in the KAIROS adapter, not in masbench: masbench only provides the defense-neutral
scenario; this module turns it into KAIROS MAS configuration.

Split of the single-agent KAIROS suite policy (`kairos/config/<suite>.yaml`), following the
cluster model of the thesis notes:

* Agent policy  = how data is labelled: revertable / non-revertable actions, taints
  (sensitivity), trusted sources. Restricted to the agent's own tools.
* Cluster policy = who may receive what: default action, clearance, contact book (other
  clusters, per-agent overrides, external parties), boundary rules. The sending cluster's
  policy decides; there is no inbound check.

Cluster policies are generated from a per-suite template plus the layout (contact book = all
other clusters at their clearance; clearances unchanged), so every partition of the sweep gets
one without hand-writing. `compose()` merges a cluster policy with its members' agent policies
back into a single-agent KAIROS policy; for L-one this reproduces the suite policy exactly
(sanity check R16 / tests).

No policy contains knowledge of a specific attack: everything is copied from the KAIROS suite
policies that were written before B1 existed.

    .venv/bin/python -m masbench.defenses.kairos       # writes layouts + policies to data/b1/
"""
from __future__ import annotations

import copy
import hashlib
from pathlib import Path
from typing import Any

import yaml

from masbench.defenses.kairos.layouts import Layout, load_layouts, scenario_dir
from masbench import io
from masbench.schema import Scenario

SOURCE = Path(__file__).resolve().parents[3] / "kairos" / "config"
HEADER = "# Generated by `python -m masbench.defenses.kairos` from kairos/config/<suite>.yaml"
DEFAULT_CLEARANCE = "high"
AGENT_FMT = "kairos-mas/agent-policy/0.1"
CLUSTER_FMT = "kairos-mas/cluster-policy/0.1"
TEMPLATE_FMT = "kairos-mas/cluster-template/0.1"


def suite_policy(suite: str) -> tuple[dict[str, Any], str]:
    path = SOURCE / f"{suite}.yaml"
    text = path.read_text()
    return yaml.safe_load(text), f"kairos/config/{suite}.yaml@sha256:{hashlib.sha256(text.encode()).hexdigest()[:12]}"


def _rule_actions(rule: dict[str, Any]) -> list[str]:
    if "sequence" in rule:
        return [s["action"] for s in rule["sequence"]]
    a = rule["match"]["action"]
    return [a] if isinstance(a, str) else list(a)


def agent_policy(s: Scenario, agent_id: str, raw: dict[str, Any], source: str) -> dict[str, Any]:
    tools = set(s.agent(agent_id).tools)
    acts = raw["context"]["actions"]
    res = raw.get("resources", {})
    return {
        "format": AGENT_FMT, "scenario": s.id, "agent": agent_id, "derived_from": source,
        "actions": {"revertable": [a for a in acts.get("revertable", []) if a in tools],
                    "non_revertable": [a for a in acts.get("non_revertable", []) if a in tools]},
        "taints": [t for t in res.get("taints", []) if t["source"] in tools],
        "trusted_sources": [t for t in res.get("trusted_sources", [])
                            if (t if isinstance(t, str) else t["source"]) in tools],
        "rate_limits": [r for r in res.get("rate_limits", []) if set(r["actions"]) & tools],
    }


def cluster_template(s: Scenario, raw: dict[str, Any], source: str) -> dict[str, Any]:
    ctx = raw["context"]
    cb = copy.deepcopy(raw.get("resources", {}).get("contact_book"))
    return {
        "format": TEMPLATE_FMT, "scenario": s.id, "derived_from": source,
        "default_action": ctx["default_action"],
        "default_clearance": DEFAULT_CLEARANCE,
        "options": {k: ctx[k] for k in ("navigational_get", "embedded_identifiers") if k in ctx},
        "external_contact_book": cb,
        "rules": copy.deepcopy(raw.get("rules", [])),
    }


def cluster_policy(s: Scenario, layout: Layout, cluster: str, template: dict[str, Any],
                   clearances: dict[str, str] | None = None) -> dict[str, Any]:
    clearances = clearances or {}
    members = layout.clusters[cluster]
    tools = {t for m in members for t in s.agent(m).tools}
    rules, dropped = [], []
    for r in template["rules"]:
        acts = _rule_actions(r)
        if "sequence" in r:
            (rules if set(acts) <= tools else dropped).append(r)
            continue
        kept = [a for a in acts if a in tools]
        if not kept:
            continue
        r = copy.deepcopy(r)
        r["match"]["action"] = kept if isinstance(r["match"]["action"], list) else kept[0]
        rules.append(r)
    pol = {
        "format": CLUSTER_FMT, "scenario": s.id, "layout": layout.id, "cluster": cluster,
        "members": members,
        "clearance": clearances.get(cluster, template["default_clearance"]),
        "default_action": template["default_action"],
        "options": template["options"],
        "contact_book": {
            "clusters": {c: {"max_level": clearances.get(c, template["default_clearance"])}
                         for c in layout.clusters if c != cluster},
            "agents": {},
            "external": template["external_contact_book"],
        },
        "rules": rules,
    }
    if dropped:
        pol["dropped_rules"] = [r["id"] for r in dropped]  # sequence spans several clusters
    return pol


def compose(agent_policies: list[dict[str, Any]], cluster: dict[str, Any], name: str) -> dict[str, Any]:
    """A single-agent KAIROS policy for the members of one cluster (parseable by kairos.policy)."""
    def union(key: str, sub: str | None = None) -> list[Any]:
        out: list[Any] = []
        for p in agent_policies:
            for x in (p[key][sub] if sub else p[key]):
                if x not in out:
                    out.append(x)
        return out

    resources: dict[str, Any] = {"taints": union("taints")}
    if union("trusted_sources"):
        resources["trusted_sources"] = union("trusted_sources")
    if union("rate_limits"):
        resources["rate_limits"] = union("rate_limits")
    if cluster["contact_book"]["external"] is not None:
        resources["contact_book"] = cluster["contact_book"]["external"]
    return {
        "version": "0.1",
        "context": {"name": name, "default_action": cluster["default_action"], **cluster["options"],
                    "actions": {"revertable": union("actions", "revertable"),
                                "non_revertable": union("actions", "non_revertable")}},
        "resources": resources,
        "rules": cluster["rules"],
    }


NAMED_LAYOUTS = ("L-single", "L-func", "L-crit", "L-one")


def write_scenario(scenario_id: str, layout_ids: tuple[str, ...] = NAMED_LAYOUTS) -> list[Path]:
    """Layouts and policies of one masbench scenario backed by a KAIROS suite policy."""
    from masbench.defenses.kairos.layouts import build_layouts, write_layouts

    s = io.load_scenario(scenario_id)
    written = [write_layouts(build_layouts(s), HEADER.replace(" from kairos/config/<suite>.yaml", ""))]
    layouts = load_layouts(s.id)
    raw, source = suite_policy(s.environment.suite)
    base = scenario_dir(s.id)
    for a in s.agents:
        p = base / "agents" / f"{a.id}.yaml"
        io.dump_yaml(agent_policy(s, a.id, raw, source), p, HEADER)
        written.append(p)
    tmpl = cluster_template(s, raw, source)
    io.dump_yaml(tmpl, base / "cluster_template.yaml", HEADER)
    written.append(base / "cluster_template.yaml")
    for lid in layout_ids:
        lay = layouts.get(lid)
        for c in lay.clusters:
            p = base / "clusters" / lid / f"{c}.yaml"
            io.dump_yaml(cluster_policy(s, lay, c, tmpl), p, HEADER)
            written.append(p)
    return written


def kairos_scenarios() -> list[str]:
    """masbench scenarios with an AgentDojo suite that has a KAIROS suite policy."""
    out = []
    for path in sorted(io.DATA.glob("*/*/scenario.yaml")):
        sid = f"{path.parent.parent.name}.{path.parent.name}"
        env = io.load_scenario(sid).environment
        if env.kind == "agentdojo" and (SOURCE / f"{env.suite}.yaml").exists():
            out.append(sid)
    return out


def write_all() -> list[Path]:
    return [p for sid in kairos_scenarios() for p in write_scenario(sid)]
